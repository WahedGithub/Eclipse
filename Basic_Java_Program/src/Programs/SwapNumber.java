package Programs;

public class SwapNumber {

	public static void main(String[] args) {
		int a =10;
		int b =20;
		System.out.println("a : " + a);
		System.out.println("b : " + b);
		int t;
		t=a;
		a=b;
		b=t;
		
		System.out.println("****Values after swapping****"
				+ " a : " + a);
		System.out.println("b : " + b);
		
		

	}

}
